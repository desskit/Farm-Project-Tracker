import { NextResponse } from 'next/server';
import { requireAdmin } from '@/lib/auth/session';
import { db, schema } from '@/db';
import { errorResponse } from '@/lib/api/errors';
import { todayISO } from '@/lib/domain/dates';

/**
 * Full JSON backup of the farm data (admin only). Excludes auth secrets:
 * password hashes and session/invite tokens are never exported.
 */
export async function GET() {
  try {
    await requireAdmin();

    const users = (await db.select().from(schema.users)).map(({ passwordHash, ...u }) => u);
    const [
      chores,
      choreCompletions,
      choreAssignees,
      assets,
      meterReadings,
      maintenanceItems,
      maintenanceLogs,
      assetDocs,
      projects,
      projectTasks,
      taskAssignees,
      projectExpenses,
      inventory,
      inventoryLog,
      notes,
      rentAssignments,
      rentCharges,
      rentDocs,
      notificationPrefs,
      activity,
      settings,
      animalGroups,
      animals,
      animalEvents,
      breedings,
      productionLogs,
      hatches,
      landUnits,
      plantings,
      perennials,
      harvests,
      landEvents,
      grazingMoves,
      rentalUnits,
      leases,
      leaseTenants,
      utilityAccounts,
      utilityBills,
      inspections,
      inspectionPhotos,
      choreSupplies,
      notices,
      guides,
      guidePhotos,
      guideLinks,
      contacts,
      sales,
      depositEntries,
    ] = await Promise.all([
      db.select().from(schema.chores),
      db.select().from(schema.choreCompletions),
      db.select().from(schema.choreAssignees),
      db.select().from(schema.assets),
      db.select().from(schema.meterReadings),
      db.select().from(schema.maintenanceItems),
      db.select().from(schema.maintenanceLogs),
      db.select().from(schema.assetDocs),
      db.select().from(schema.projects),
      db.select().from(schema.projectTasks),
      db.select().from(schema.taskAssignees),
      db.select().from(schema.projectExpenses),
      db.select().from(schema.inventory),
      db.select().from(schema.inventoryLog),
      db.select().from(schema.notes),
      db.select().from(schema.rentAssignments),
      db.select().from(schema.rentCharges),
      db.select().from(schema.rentDocs),
      db.select().from(schema.notificationPrefs),
      db.select().from(schema.activity),
      db.select().from(schema.settings),
      db.select().from(schema.animalGroups),
      db.select().from(schema.animals),
      db.select().from(schema.animalEvents),
      db.select().from(schema.breedings),
      db.select().from(schema.productionLogs),
      db.select().from(schema.hatches),
      db.select().from(schema.landUnits),
      db.select().from(schema.plantings),
      db.select().from(schema.perennials),
      db.select().from(schema.harvests),
      db.select().from(schema.landEvents),
      db.select().from(schema.grazingMoves),
      db.select().from(schema.rentalUnits),
      db.select().from(schema.leases),
      db.select().from(schema.leaseTenants),
      db.select().from(schema.utilityAccounts),
      db.select().from(schema.utilityBills),
      db.select().from(schema.inspections),
      db.select().from(schema.inspectionPhotos),
      db.select().from(schema.choreSupplies),
      db.select().from(schema.notices),
      db.select().from(schema.guides),
      db.select().from(schema.guidePhotos),
      db.select().from(schema.guideLinks),
      db.select().from(schema.contacts),
      db.select().from(schema.sales),
      db.select().from(schema.depositEntries),
    ]);

    const backup = {
      exportedAt: new Date().toISOString(),
      version: 1,
      users,
      chores,
      choreCompletions,
      choreAssignees,
      assets,
      meterReadings,
      maintenanceItems,
      maintenanceLogs,
      assetDocs,
      projects,
      projectTasks,
      taskAssignees,
      projectExpenses,
      inventory,
      inventoryLog,
      notes,
      rentAssignments,
      rentCharges,
      rentDocs,
      notificationPrefs,
      activity,
      settings,
      animalGroups,
      animals,
      animalEvents,
      breedings,
      productionLogs,
      hatches,
      landUnits,
      plantings,
      perennials,
      harvests,
      landEvents,
      grazingMoves,
      rentalUnits,
      leases,
      leaseTenants,
      utilityAccounts,
      utilityBills,
      inspections,
      inspectionPhotos,
      choreSupplies,
      notices,
      guides,
      guidePhotos,
      guideLinks,
      contacts,
      sales,
      depositEntries,
    };

    return new NextResponse(JSON.stringify(backup, null, 2), {
      headers: {
        'Content-Type': 'application/json',
        'Content-Disposition': `attachment; filename="farm-backup-${todayISO()}.json"`,
      },
    });
  } catch (e) {
    return errorResponse(e);
  }
}
